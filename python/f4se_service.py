@app.post("/scaffold")
def scaffold(req: ScaffoldRequest):
    """Generate a complete F4SE plugin project scaffold."""
    if not JINJA2_AVAILABLE:
        return {
            "status": "unavailable",
            "message": "jinja2 is not installed. Run: pip install jinja2",
        }

    env = _make_env()
    if env is None:
        return {"status": "error", "message": "Failed to create Jinja2 environment"}

    plugin_id = _slugify(req.plugin_name)
    ctx = {
        "plugin_name":     req.plugin_name,
        "plugin_id":       plugin_id,
        "author":          req.author,
        "version_major":   req.version_major,
        "version_minor":   req.version_minor,
        "version_patch":   req.version_patch,
        "hooks":           req.hooks,
        "has_papyrus":     req.has_papyrus,
        "use_address_library": req.use_address_library,
        "trampoline_size": req.trampoline_size,
    }

    files: Dict[str, str] = {
        "CMakeLists.txt":      _render(env, _CMAKELISTS_TMPL, ctx),
        "CMakePresets.json":   _render(env, _CMAKE_PRESET_TMPL, ctx),
        "vcpkg.json":          _render(env, _VCPKG_JSON_TMPL, ctx),
        "README.md":           _render(env, _README_TMPL, ctx),
        f"src/main.cpp":       _render(env, _MAIN_CPP_TMPL, ctx),
    }

    # Optionally write to disk — guard against path traversal in template keys
    written: List[str] = []
    errors: List[str] = []
    if req.output_dir:
        base = Path(req.output_dir).resolve()
        for rel_path, content in files.items():
            try:
                # Resolve the destination and ensure it stays inside base
                dest = (base / rel_path).resolve()
                if not str(dest).startswith(str(base)):
                    errors.append(f"{rel_path}: rejected (path traversal)")
                    continue
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(content, encoding="utf-8")
                written.append(str(dest))
            except OSError as e:
                errors.append(f"{rel_path}: write error")

    return {
        "status": "ok",
        "plugin_name": req.plugin_name,
        "plugin_id": plugin_id,
        "files": files,
        "written": written,
        "errors": errors,
    }


