"""
F4SE Plugin Scaffolder Service — port 8016
Generates ready-to-compile F4SE (Fallout 4 Script Extender) C++ plugin stubs
using Jinja2 templates.

F4SE GitHub: https://github.com/ianpatt/f4se
CommonLib-F4 (modern header-only F4SE SDK): https://github.com/Ryan-rsm-McKenzie/CommonLibF4

The service fills in:
  - Plugin version manifest (F4SE version, runtime version, plugin name/author)
  - CMakeLists.txt with vcpkg integration
  - main.cpp stub with the required F4SEPlugin_Query / F4SEPlugin_Load exports
  - Optional event hooks (OnMessage, OnCameraStateChanged, etc.)
  - Optional papyrus function registration scaffold
  - Optional MCM helper stub (F4SE MCM support)

All output is generated in-memory and returned as a file map so the React
component can write the tree to disk via the native `files` IPC.
"""
