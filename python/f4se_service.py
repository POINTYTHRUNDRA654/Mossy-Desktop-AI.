# ── Jinja2 environment ────────────────────────────────────────────────────

def _make_env() -> Optional[object]:
    if not JINJA2_AVAILABLE:
        return None
    return Environment(
        loader=BaseLoader(),
        autoescape=False,
        trim_blocks=True,
        lstrip_blocks=True,
    )


def _render(env, template_str: str, ctx: dict) -> str:
    tmpl = env.from_string(template_str)
    return tmpl.render(**ctx)


def _slugify(name: str) -> str:
    """Convert display name to a safe C identifier / filename stem."""
    s = re.sub(r"[^\w]", "_", name)
    s = re.sub(r"_+", "_", s).strip("_")
    return s or "MyPlugin"


# ── Request / response models ─────────────────────────────────────────────

class ScaffoldRequest(BaseModel):
    plugin_name: str
    author: str = "Unknown"
    version_major: int = 1
    version_minor: int = 0
    version_patch: int = 0
    hooks: List[str] = []          # e.g. ["DataLoaded", "NewGame", "LoadGame"]
    has_papyrus: bool = False      # include Papyrus registration scaffold
    use_address_library: bool = True
    trampoline_size: int = 64
    output_dir: Optional[str] = None  # if set, write files to disk


